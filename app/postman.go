// postmanFile is the name of the generated Postman collection.
const postmanFile = "reinvent.postman_collection.json"

// postmanCollection builds a Postman v2.1 collection from the scenario:
// "1. Run the demo" (every step in order) and "2. Resolve the demo".
//
//   - Routing keys are empty collection variables: the collection never
//     contains a key, so it's safe to share. Paste them in Postman.
//   - The first request sets {{run_id}}; every alert's dedup_key ends in it,
//     so each collection run opens fresh incidents (same as the app).
//   - Timestamps are computed when the request is sent (pre-request script),
//     keeping their offset: the 47-minutes-ago deploy is always 47 minutes ago.
//   - A test script waits the step's wait_after, so the Collection Runner
//     keeps the demo's pacing, and checks for 202 Accepted.
func postmanCollection(sc *Scenario) ([]byte, error) {
	changeVar := func(svc string) string { return "change_key_" + strings.ReplaceAll(svc, "-", "_") }
	changeVars := map[string]string{} // variable name → service

	var runItems, resolveItems []any
	for i, st := range sc.Steps {
		body, err := sc.render(st)
		if err != nil {
			return nil, err
		}
		svc := routedTo(body)
		path := []string{"v2", "enqueue"}
		desc := fmt.Sprintf("Routed by the Payments Demo orchestration to **%s** (custom_details.service).", svc)
		if st.Type == "change" {
			path = []string{"v2", "change", "enqueue"}
			v := changeVar(svc)
			changeVars[v] = svc
			body["routing_key"] = "{{" + v + "}}"
			desc = fmt.Sprintf("Change event, sent straight to **%s** with its change integration key.", svc)
		} else {
			body["routing_key"] = "{{orchestration_routing_key}}"
			if p, ok := body["payload"].(map[string]any); ok {
				delete(p, "timestamp") // PagerDuty uses the time it receives the alert
			}
			if k, ok := body["dedup_key"].(string); ok {
				body["dedup_key"] = k + "/{{run_id}}"
			}
		}

		pre := timestampVars(body, fmt.Sprintf("s%02d", i+1))
		if i == 0 {
			pre = append([]string{
				"// New run ID: every alert's dedup_key ends in it, so each run opens fresh incidents.",
				`pm.collectionVariables.set("run_id", "run-" + Date.now().toString(36));`,
			}, pre...)
		}
		wait, _ := time.ParseDuration(st.WaitAfter)
		item, err := postmanRequest(fmt.Sprintf("%02d %s", i+1, st.Name), desc, path, body, pre, wait)
		if err != nil {
			return nil, err
		}
		runItems = append(runItems, item)

		if st.Type == "alert" {
			body["event_action"] = "resolve"
			ritem, err := postmanRequest(fmt.Sprintf("Resolve %02d %s", i+1, st.Name),
				"Resolves this alert from the most recent collection run ({{run_id}}).", path, body,
				timestampVars(body, fmt.Sprintf("r%02d", i+1)), 0)
			if err != nil {
				return nil, err
			}
			resolveItems = append(resolveItems, ritem)
		}
	}

	vars := []any{
		map[string]any{"key": "events_url", "value": "https://events.pagerduty.com", "description": "EU accounts: https://events.eu.pagerduty.com"},
		map[string]any{"key": "orchestration_routing_key", "value": "", "description": "Paste yours: PagerDuty → Automation → Event Orchestration → Payments Demo → Integrations (or `terraform output -raw routing_key`)"},
	}
	names := make([]string, 0, len(changeVars))
	for k := range changeVars {
		names = append(names, k)
	}
	sort.Strings(names)
	for _, k := range names {
		vars = append(vars, map[string]any{"key": k, "value": "", "description": fmt.Sprintf("Paste yours: service %s → Integrations → \"CI/CD change events\" integration key (or `terraform output -json change_routing_keys`)", changeVars[k])})
	}
	vars = append(vars, map[string]any{"key": "run_id", "value": "run-manual", "description": "Set by the first request of each run"})

	id := sha1.Sum([]byte("reinvent:" + sc.Name))
	coll := map[string]any{
		"info": map[string]any{
			"_postman_id": fmt.Sprintf("%x-%x-%x-%x-%x", id[0:4], id[4:6], id[6:8], id[8:10], id[10:16]),
			"name":        "Reinvent: " + sc.Name,
			"description": "Generated by Reinvent (`./trigger export`) from payloads/scenario.json. Don't edit by hand; re-export.\n\n" +
				"This collection contains no keys. \n\n" +
				"1. Paste your keys into the collection variables: `orchestration_routing_key` and each `change_key_*` (each variable says where to find it). EU accounts: set `events_url` to https://events.eu.pagerduty.com.\n" +
				"2. Run the folder **1. Run the demo** with the Collection Runner. The requests keep the demo's pacing themselves.\n" +
				"3. When you're done, run **2. Resolve the demo**. It resolves the most recent run.",
			"schema": "https://schema.getpostman.com/json/collection/v2.1.0/collection.json",
		},
		"item": []any{
			map[string]any{"name": "1. Run the demo", "description": "Every event in order, about 30 seconds in the Collection Runner.", "item": runItems},
			map[string]any{"name": "2. Resolve the demo", "description": "Resolves every alert from the most recent run.", "item": resolveItems},
		},
		"variable": vars,
	}
	return marshalPretty(coll)
}

func postmanRequest(name, desc string, path []string, body map[string]any, pre []string, wait time.Duration) (map[string]any, error) {
	raw, err := marshalPretty(body)
	if err != nil {
		return nil, err
	}
	test := []string{`pm.test("PagerDuty accepted the event (202)", function () { pm.response.to.have.status(202); });`}
	if wait > 0 {
		test = append(test, fmt.Sprintf("// Keep the demo's pacing in the Collection Runner.\nsetTimeout(function () {}, %d);", wait.Milliseconds()))
	}
	events := []any{map[string]any{"listen": "test", "script": map[string]any{"type": "text/javascript", "exec": test}}}
	if len(pre) > 0 {
		events = append([]any{map[string]any{"listen": "prerequest", "script": map[string]any{"type": "text/javascript", "exec": pre}}}, events...)
	}
	return map[string]any{
		"name":  name,
		"event": events,
		"request": map[string]any{
			"method":      "POST",
			"description": desc,
			"header":      []any{map[string]any{"key": "Content-Type", "value": "application/json"}},
			"body": map[string]any{
				"mode":    "raw",
				"raw":     strings.TrimSpace(string(raw)),
				"options": map[string]any{"raw": map[string]any{"language": "json"}},
			},
			"url": map[string]any{
				"raw":  "{{events_url}}/" + strings.Join(path, "/"),
				"host": []string{"{{events_url}}"},
				"path": path,
			},
		},
	}, nil
}

// timestampVars replaces every RFC 3339 time in body with a {{variable}} and
// returns the pre-request lines that set it at send time, keeping its offset
// from now (rounded to the minute).
func timestampVars(body map[string]any, prefix string) []string {
	var lines []string
	n := 0
	var walk func(v any) any
	walk = func(v any) any {
		switch x := v.(type) {
		case map[string]any:
			keys := make([]string, 0, len(x))
			for k := range x {
				keys = append(keys, k)
			}
			sort.Strings(keys)
			for _, k := range keys {
				x[k] = walk(x[k])
			}
		case []any:
			for i := range x {
				x[i] = walk(x[i])
			}
		case string:
			t, err := time.Parse(time.RFC3339, x)
			if err != nil {
				return x
			}
			n++
			name := fmt.Sprintf("%s_ts%d", prefix, n)
			mins := int(math.Round(time.Since(t).Minutes()))
			lines = append(lines, fmt.Sprintf(`pm.variables.set("%s", new Date(Date.now() - %d * 60000).toISOString()); // %d minutes ago`, name, mins, mins))
			return "{{" + name + "}}"
		}
		return v
	}
	walk(body)
	return lines
}
